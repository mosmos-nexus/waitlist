// ---- 5. GrowthOrbit: dragging the ring advances cycles and grows Mos ----
{
  const { ctx, p } = await page('/');
  await p.locator('.growth .scene').scrollIntoViewIfNeeded();
  await p.waitForTimeout(400);

  const { cx, cy, r } = await ringGeometry(p);

  const scale0 = await p.locator('.growth .core').evaluate((el) => getComputedStyle(el).transform);

  // Two full turns around the centre.
  await p.mouse.move(cx + r, cy);
  await p.mouse.down();
  for (let turn = 0; turn < 2; turn++) {
    for (let a = 0; a <= 360; a += 12) {
      const rad = (a * Math.PI) / 180;
      await p.mouse.move(cx + Math.cos(rad) * r, cy + Math.sin(rad) * r);
    }
  }
  await p.mouse.up();
  await p.waitForTimeout(900);

  const cycleText = await p.locator('.growth .cycle').innerText();
  ok('turning the ring counts cycles', /[1-9]/.test(cycleText), JSON.stringify(cycleText));

  const scale1 = await p.locator('.growth .core').evaluate((el) => getComputedStyle(el).transform);
  ok('Mos grows with cycles', scale0 !== scale1);

  const globs = await p.locator('.growth .glob').count();
  ok('cycles add inner globs', globs > 2, `${globs} globs`);

  await ctx.close();
}

// ---- 6. Mobile: island survives, layers thinned ----
{
  const ctx = await browser.newContext({
    viewport: { width: 390, height: 844 },
    hasTouch: true,
    isMobile: true,
  });
  const p = await ctx.newPage();
  p.on('pageerror', (e) => errors.push(`[pageerror mobile] ${e.message}`));
  await p.goto(BASE + '/', { waitUntil: 'networkidle' });
  await p.waitForTimeout(1400);

  ok('island kept on mobile', (await p.locator('svg.isle[role="img"]').count()) === 1);

  const d = await p.locator('.hero [data-anim="mos-fill"]').getAttribute('d');
  ok('Mos renders on mobile', !!d && d.length > 200);

  const visibleMotes = await p
    .locator('.hero .mote')
    .evaluateAll((els) => els.filter((e) => getComputedStyle(e).display !== 'none').length);
  ok('motes thinned on mobile', visibleMotes === 4, `${visibleMotes} visible`);

  const innerOrbit = await p
    .locator('.orbit-plane.inner')
    .evaluate((el) => getComputedStyle(el).display);
  ok('inner orbit hidden on mobile', innerOrbit === 'none', innerOrbit);

  const cursor = await p.evaluate(() => getComputedStyle(document.body).cursor);
  ok('no cursor takeover on touch', cursor !== 'none', cursor);

  await ctx.close();
}

