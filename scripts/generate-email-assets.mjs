// Generates base64-embedded PNGs for the welcome email (src/lib/server/email-assets.ts).
// Email clients don't render webp/SVG, and external image URLs break before the site is
// deployed or when a client blocks remote images — so we inline the brand art as CID
// attachments instead. Re-run after the source character art changes:
//   node scripts/generate-email-assets.mjs
import sharp from 'sharp';
import { writeFileSync } from 'node:fs';

const SRC = 'static/characters';
const assets = [
  { name: 'mosGreeting', src: `${SRC}/mos-greeting.webp`, width: 320 }, // hero (display ~240px)
  { name: 'mosHappy', src: `${SRC}/mos-happy.webp`, width: 80 }, // sign-off avatar (display ~36px)
];

// Palette-quantized PNG keeps transparency but stays small — the whole email must clear
// Gmail's ~102 KB clipping limit once base64-encoded.
const lines = [];
for (const a of assets) {
  const buf = await sharp(a.src)
    .resize({ width: a.width, withoutEnlargement: true })
    .png({ palette: true, quality: 78, colors: 128, effort: 10, compressionLevel: 9 })
    .toBuffer();
  lines.push(`export const ${a.name} = '${buf.toString('base64')}';`);
  console.log(`${a.name}: ${(buf.length / 1024).toFixed(1)} KB`);
}

const header = `// AUTO-GENERATED by scripts/generate-email-assets.mjs — do not edit by hand.
// Base64 PNGs inlined into the welcome email as CID attachments. Email clients can't be
// trusted to render webp/SVG or remote image URLs, so the brand art travels with the mail.
`;
writeFileSync('src/lib/server/email-assets.ts', header + lines.join('\n') + '\n');
console.log('wrote src/lib/server/email-assets.ts');
